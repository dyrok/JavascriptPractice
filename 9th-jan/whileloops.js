let i = 0;

while (i < 6) {
    console.log(i);
    i++;
}

do {
    console.log(i);
    i++;
} while (i < 10);

//syntax format for do loops
// do {
//     //code block to be executed
// } while (condition);
// The do...while loop will always execute the code block once,
// before checking if the condition is true, then it will repeat the loop as long as the condition is true.
// Whearas in while loop, the condition is checked first, and if it is true, the code block is executed.   